#!/usr/bin/env bash
set -euo pipefail

mkdir -p docs
{
  echo "# Load-test results"
  echo
  echo "Generated by \`make loadtest\` on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
  echo
  echo '```text'
  if command -v k6 >/dev/null 2>&1; then
    k6 run loadtest/k6.js
  else
    python3 scripts/loadtest_fallback.py
  fi
  echo '```'
} | tee docs/results.md
