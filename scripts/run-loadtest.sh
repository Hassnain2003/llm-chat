#!/usr/bin/env bash
set -euo pipefail

mkdir -p docs
{
  echo "# Load-test results"
  echo
  echo "Generated by \`make loadtest\` on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
  echo
  echo "Before using these numbers, record the hardware, exact model and quantization,"
  echo "UTC date, and command/environment used for the run."
  echo
  echo "- Hardware: TODO"
  echo "- Model: ${MODEL:-tinyllama}"
  echo "- Quantization: TODO"
  echo "- Command: \`make loadtest\`"
  echo "- Base URL: ${BASE_URL:-http://localhost:8080}"
  echo
  echo '```text'
  if command -v k6 >/dev/null 2>&1; then
    k6 run --quiet loadtest/k6.js | sed 's/[[:space:]]*$//'
  else
    python3 scripts/loadtest_fallback.py
  fi
  echo '```'
} | tee docs/results.md
